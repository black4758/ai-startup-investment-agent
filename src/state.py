from typing import TypedDict, List


class GraphState(TypedDict):
    # ── 기업 큐 관리 ────────────────────────────────────────────────
    # 작성: 초기화 / 사용: 후보 기업 추출
    candidates: List[str]

    # 작성: 후보 기업 추출 / 사용: 1~3번 에이전트
    current_startup: str

    # ── 기술성 평가 에이전트 ─────────────────────────────────────────
    # 작성: 기술성 평가 / 사용: 투자 판단, 보고서 생성
    tech_analysis: str

    # 작성: 기술성 평가 / 사용: 투자 판단
    # 기술 차별성 및 특허, 구매이유 점수와 근거
    tech_scores: dict

    # ── 기업 평가 에이전트 ──────────────────────────────────────────
    # 작성: 기업 평가 / 사용: 투자 판단, 보고서 생성
    company_analysis: str

    # 작성: 기업 평가 / 사용: 투자 판단
    # 창업자, 실적, 수익모델 점수와 근거
    company_scores: dict

    # ── 시장성 평가 에이전트 ─────────────────────────────────────────
    # 작성: 시장성 평가 / 사용: 투자 판단, 보고서 생성
    market_analysis: str

    # 작성: 시장성 평가 / 사용: 투자 판단
    # 시장 내 포지션 및 진입장벽, 시장성 점수와 근거
    market_scores: dict

    # ── 투자 판단 에이전트 ──────────────────────────────────────────
    # 작성: 1~3번 에이전트 / 사용: 투자 판단, 재검색
    missing_items: List[str]

    # 작성: 투자 판단 / 사용: 분기, 보고서 생성
    total_score: float

    # 작성: 투자 판단 / 사용: 분기, 보고서 생성
    # "PASS" / "HOLD" / "DROP"
    decision: str

    # 작성: 투자 판단 / 사용: 분기
    # 현재 기업 재평가 횟수 (최대 1)
    retry_count: int

    # ── 누적 관리 ────────────────────────────────────────────────────
    # 작성: 투자 판단 / 사용: 분기, 보고서 생성
    evaluations: List[dict]

    # 작성: 1~3번 에이전트 / 사용: 보고서 생성
    sources: List[str]

    # ── 최종 산출물 ──────────────────────────────────────────────────
    # 작성: 보고서 생성 / 사용: 출력
    report: str
